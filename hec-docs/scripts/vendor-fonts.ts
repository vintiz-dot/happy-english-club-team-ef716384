// Copies the pinned Fontsource woff2 files (latin, latin-ext, vietnamese
// subsets) into fonts/ and writes fonts/fonts.css with their unicode-ranges.
// The output is committed, so rendering never needs node_modules or a network.
// Re-run only when the font versions in package.json change.
import { readFile, writeFile, copyFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { ROOT } from "../src/config.ts";

const FAMILIES: { pkg: string; weights: number[]; italics: number[] }[] = [
  { pkg: "cormorant-garamond", weights: [500, 600, 700], italics: [500] },
  { pkg: "be-vietnam-pro", weights: [400, 500, 600, 700], italics: [400] },
  // Fallbacks for characters teachers paste (arrows, symbols, emoji). Bundled
  // so a missing glyph never reaches for whatever system font the host has.
  { pkg: "noto-sans-math", weights: [400], italics: [] },
  { pkg: "noto-sans-symbols-2", weights: [400], italics: [] },
  { pkg: "noto-emoji", weights: [400], italics: [] },
];
const SUBSETS = new Set(["latin", "latin-ext", "vietnamese", "symbols", "math", "emoji"]);
const isSubset = (s: string) => SUBSETS.has(s) || /^\[?\d+\]?$/.test(s); // noto-emoji ships numbered subsets: "[0]"

const outDir = path.join(ROOT, "fonts");
await mkdir(outDir, { recursive: true });
const licences: string[] = [];
let css = "/* Generated by scripts/vendor-fonts.ts. Fonts: SIL Open Font License 1.1 (see fonts/LICENSES.md). */\n";

for (const fam of FAMILIES) {
  const base = path.join(ROOT, "node_modules", "@fontsource", fam.pkg);
  const version = JSON.parse(await readFile(path.join(base, "package.json"), "utf8")).version;
  licences.push(`## @fontsource/${fam.pkg}@${version}\n\n` + (await readFile(path.join(base, "LICENSE"), "utf8")));
  const sheets = [...fam.weights.map((w) => `${w}.css`), ...fam.italics.map((w) => `${w}-italic.css`)];
  css += `\n/* @fontsource/${fam.pkg}@${version} */\n`;
  for (const sheet of sheets) {
    const src = await readFile(path.join(base, sheet), "utf8");
    for (const block of src.split("/*").slice(1)) {
      const subset = block
        .slice(0, block.indexOf("*/"))
        .trim()
        .replace(`${fam.pkg}-`, "")
        .replace(/-\d+-(normal|italic)$/, "");
      if (!isSubset(subset)) continue;
      const face = block.slice(block.indexOf("@font-face"));
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(face)?.[1];
      if (!file) continue;
      await copyFile(path.join(base, "files", file), path.join(outDir, file));
      css += face
        .replace(/src:[^;]+;/, `src: url(./${file}) format('woff2');`)
        .replace(/font-display:[^;]+;/, "font-display: block;")
        .trim() + "\n";
    }
  }
}
await writeFile(path.join(outDir, "fonts.css"), css);
await writeFile(path.join(outDir, "LICENSES.md"), "# Bundled font licences\n\n" + licences.join("\n\n"));
console.log("fonts vendored to", outDir);
