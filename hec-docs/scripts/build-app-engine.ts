// Builds the HEC Docs engine for the web app and copies the print assets:
//
//   ../src/lib/hecDocs/engine.generated.js   one self-contained ES module
//   ../public/hec-docs/                       fonts, styles, logo, blank.html
//
// Templates are precompiled (no eval in the browser), JSON Schemas become
// Ajv standalone validators, and the tenant theme is embedded. The app needs
// no new npm dependencies. Run after changing any template, component,
// schema, token or tenant file:  npm run build:app
import { readFile, writeFile, mkdir, readdir, rm, cp, stat } from "node:fs/promises";
import path from "node:path";
import nunjucks from "nunjucks";
import { Ajv2020 } from "ajv/dist/2020.js";
import addFormatsModule from "ajv-formats";
import standaloneModule from "ajv/dist/standalone/index.js";
import { build } from "esbuild";
import { ROOT } from "../src/config.ts";
import { getRegistry } from "../src/templates/registry.ts";
import { loadTenant } from "../src/tenant.ts";
import { ENGINE_VERSION } from "../src/render/render.ts";

const addFormats = ((addFormatsModule as unknown as { default?: unknown }).default ?? addFormatsModule) as (a: Ajv2020) => void;
const standaloneCode = ((standaloneModule as unknown as { default?: unknown }).default ?? standaloneModule) as (a: Ajv2020, refs: Record<string, string>) => string;

const APP = path.resolve(ROOT, "..");
const GEN = path.join(ROOT, "app", "generated");
const OUT_JS = path.join(APP, "src", "lib", "hecDocs", "engine.generated.js");
const PUBLIC = path.join(APP, "public", "hec-docs");

await rm(GEN, { recursive: true, force: true });
await mkdir(GEN, { recursive: true });

// 1. Precompiled templates (same options as the service's environment).
const env = new nunjucks.Environment(null, { autoescape: true, throwOnUndefined: true, trimBlocks: true, lstripBlocks: true });
async function walk(dir: string, base = dir): Promise<string[]> {
  const out: string[] = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === "fixtures") continue;
      out.push(...(await walk(p, base)));
    } else if (e.name.endsWith(".njk")) out.push(path.relative(base, p).split(path.sep).join("/"));
  }
  return out;
}
let precompiled = "";
for (const root of ["templates", "components"]) {
  for (const name of await walk(path.join(ROOT, root))) {
    const src = await readFile(path.join(ROOT, root, name), "utf8");
    precompiled += nunjucks.precompileString(src, { name, env }) + "\n";
  }
}
const registry = await getRegistry();
for (const [type, e] of registry) {
  precompiled += nunjucks.precompileString(e.manifest.documentTitle, { name: `__title__/${type}`, env }) + "\n";
}
await writeFile(
  path.join(GEN, "templates.js"),
  `// Generated by scripts/build-app-engine.ts. Do not edit.\nconst window = {};\n${precompiled}\nexport default window.nunjucksPrecompiled;\n`,
);

// 2. Standalone validators.
const ajv = new Ajv2020({ allErrors: true, strict: true, allowUnionTypes: true, code: { source: true, esm: true } });
addFormats(ajv);
ajv.addKeyword({ keyword: "x-brand", schemaType: "boolean" });
const refs: Record<string, string> = {};
const manifests: Record<string, unknown> = {};
for (const [type, e] of registry) {
  const schema = JSON.parse(await readFile(path.join(e.dir, "schema.json"), "utf8"));
  ajv.addSchema(schema);
  const fn = `validate_${type.replace(/-/g, "_")}`;
  refs[fn] = schema.$id;
  manifests[type] = { ...e.manifest, validator: fn };
}
await writeFile(path.join(GEN, "validators.js"), `// Generated. Do not edit.\n${standaloneCode(ajv, refs)}\n`);

// 3. Data: manifests, tenant theme (no filesystem paths), component styles.
const tenant = await loadTenant("hec");
const { dir: _dir, tokens: _tokens, ...tenantData } = tenant;
void _dir;
void _tokens;
const componentStyles = (await readdir(path.join(ROOT, "components", "css"))).filter((f) => f.endsWith(".css")).sort();
await writeFile(
  path.join(GEN, "data.js"),
  `// Generated. Do not edit.\nexport const ENGINE_VERSION = ${JSON.stringify(ENGINE_VERSION)};\nexport const MANIFESTS = ${JSON.stringify(manifests, null, 1)};\nexport const TENANT = ${JSON.stringify(tenantData, null, 1)};\nexport const COMPONENT_STYLES = ${JSON.stringify(componentStyles)};\n`,
);

// 4. Filter plugins, statically imported.
const filterFiles = (await readdir(path.join(ROOT, "src", "templates", "filters"))).filter((f) => f.endsWith(".ts")).sort();
await writeFile(
  path.join(GEN, "filters.js"),
  `// Generated. Do not edit.\n${filterFiles.map((f, i) => `import { filters as f${i} } from "../../src/templates/filters/${f}";`).join("\n")}\nexport const PLUGIN_FILTERS = Object.assign({}, ${filterFiles.map((_, i) => `f${i}`).join(", ") || "{}"});\n`,
);

// 5. Bundle.
await mkdir(path.dirname(OUT_JS), { recursive: true });
const result = await build({
  entryPoints: [path.join(ROOT, "app", "entry.ts")],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "eof",
  outfile: OUT_JS,
  banner: { js: "// Generated by hec-docs/scripts/build-app-engine.ts. Do not edit: change hec-docs and run `npm run build:app` there.\n/* eslint-disable */" },
  logLevel: "warning",
  metafile: true,
});
const bytes = (await stat(OUT_JS)).size;

// 6. Print assets, served by the app's own site at /hec-docs/.
await rm(PUBLIC, { recursive: true, force: true });
await mkdir(path.join(PUBLIC, "components", "css"), { recursive: true });
await cp(path.join(ROOT, "fonts"), path.join(PUBLIC, "fonts"), { recursive: true, filter: (s) => !s.endsWith(".md") });
await cp(path.join(ROOT, "components", "hec.css"), path.join(PUBLIC, "components", "hec.css"));
for (const f of componentStyles) await cp(path.join(ROOT, "components", "css", f), path.join(PUBLIC, "components", "css", f));
await mkdir(path.join(PUBLIC, "tenant", "assets"), { recursive: true });
await cp(path.join(tenant.dir, tenant.logo.file), path.join(PUBLIC, "tenant", tenant.logo.file));
// The printer opens this first so the document has the site's origin and
// can load the fonts and styles above without cross-origin rules.
await writeFile(path.join(PUBLIC, "blank.html"), "<!doctype html><html><head><meta charset=\"utf-8\"><title>HEC Docs</title></head><body></body></html>\n");
await writeFile(
  path.join(PUBLIC, "README.md"),
  "Print assets for HEC Docs (fonts, styles, logo). Generated by hec-docs/scripts/build-app-engine.ts; do not edit here.\nFonts: SIL Open Font License 1.1 (see hec-docs/fonts/LICENSES.md).\n",
);
console.log(`engine: ${path.relative(APP, OUT_JS)} (${(bytes / 1024).toFixed(0)} KB); assets: public/hec-docs; inputs: ${Object.keys(result.metafile.inputs).length}`);
