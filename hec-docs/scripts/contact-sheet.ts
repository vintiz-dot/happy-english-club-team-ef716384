// Before/after contact sheet: for every fixture that names a `before`
// baseline, the original generator's page 1 next to the new page 1 (and the
// variants of the same family underneath). Output: qa/contact-sheet.pdf and
// one PNG per family in qa/contact/.
//
//   node scripts/contact-sheet.ts
import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { ROOT } from "../src/config.ts";
import { render } from "../src/render/render.ts";
import { rasterise } from "../src/qa/raster.ts";
import { getRegistry } from "../src/templates/registry.ts";
import { loadTenant } from "../src/tenant.ts";
import { openIsolatedPage, ASSET_ORIGIN, closeBrowser } from "../src/render/browser.ts";

const QA = path.join(ROOT, "qa");
const OUT = path.join(QA, "contact");
await mkdir(OUT, { recursive: true });

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);
const files: Record<string, Buffer> = {};
let n = 0;
const add = (buf: Buffer) => {
  const key = `/img/${n++}.png`;
  files[key] = buf;
  return key;
};

interface Cell { label: string; img: string; note?: string }
const sections: { title: string; before: Cell[]; after: Cell[] }[] = [];

for (const [type, entry] of await getRegistry()) {
  const fxDir = path.join(entry.dir, "fixtures");
  const fixtures = (await readdir(fxDir)).filter((f) => f.endsWith(".json")).sort();
  const before: Cell[] = [];
  const after: Cell[] = [];
  const seenBefore = new Set<string>();
  for (const f of fixtures) {
    const fx = JSON.parse(await readFile(path.join(fxDir, f), "utf8"));
    const r = await render({ type, data: fx.data, variant: fx.variant, tenant: fx.tenant, generatedAt: fx.generatedAt });
    const pages = r.contentType === "application/pdf" ? (await rasterise(r.body, { dpi: 72, maxPages: 2 })).pages.map((p) => p.png) : [r.body];
    after.push({ label: `${r.variant}${fx.before ? "" : " (extra fixture)"} · ${f.replace(/\.json$/, "")}`, img: add(pages[0]), note: `${r.pages} p · ${(r.bytes / 1024).toFixed(0)} KB · ${r.filename}` });
    if (fx.before && !seenBefore.has(fx.before)) {
      seenBefore.add(fx.before);
      const dir = path.join(QA, "before", fx.before);
      const img = ["page-p1.png", "page-card.png", "screen-preview.png"].map((p) => path.join(dir, p)).find((p) => existsSync(p));
      if (img) before.push({ label: `original · ${fx.before}`, img: add(await readFile(img)), note: fx.before === "invoice-single" ? "the original print path produced a blank page; this is the on-screen view" : undefined });
    }
  }
  sections.push({ title: `${entry.manifest.title} (${type}@${entry.manifest.version})`, before, after });
}

const tenant = await loadTenant("hec");
const cell = (c: Cell) => `<figure><img src="${c.img}" alt="${esc(c.label)}"><figcaption><b>${esc(c.label)}</b>${c.note ? `<br>${esc(c.note)}` : ""}</figcaption></figure>`;
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>HEC Docs before and after</title>
<link rel="stylesheet" href="/fonts/fonts.css"><style>${tenant.css}
@page { size: A3 landscape; margin: 12mm; background: var(--color-paper); }
body { margin: 0; font-family: var(--font-family-body); color: var(--color-ink); background: var(--color-paper); font-size: 8pt; }
h1 { font-family: var(--font-family-display); font-size: 22pt; margin: 0 0 4pt; }
h2 { font-family: var(--font-family-display); font-size: 15pt; margin: 0 0 6pt; border-bottom: 0.5pt solid var(--color-gold); padding-bottom: 3pt; }
section { break-before: page; }
section:first-of-type { break-before: auto; }
.row { display: flex; gap: 10mm; align-items: flex-start; }
.col { display: flex; flex-wrap: wrap; gap: 5mm; }
.before { flex: none; border-right: 0.5pt solid var(--color-rule); padding-right: 10mm; }
figure { margin: 0; width: 62mm; break-inside: avoid; }
figure img { width: 100%; border: 0.5pt solid var(--color-rule); display: block; background: #fff; }
figcaption { margin-top: 2pt; color: var(--color-muted); line-height: 1.35; overflow-wrap: anywhere; }
.k { font-size: 7pt; letter-spacing: .06em; text-transform: uppercase; color: var(--color-gold-ink); margin-bottom: 3pt; font-weight: 600; }
</style></head><body>
<h1>HEC Docs: before and after</h1>
<p>Left: page 1 of the original generator with the same made-up data. Right: the new template, every variant. Generated by scripts/contact-sheet.ts.</p>
${sections.map((s) => `<section><h2>${esc(s.title)}</h2><div class="row">
<div class="before"><div class="k">Before</div><div class="col">${s.before.map(cell).join("") || "<p>(no original: new fixture)</p>"}</div></div>
<div><div class="k">After</div><div class="col">${s.after.map(cell).join("")}</div></div></div></section>`).join("\n")}
</body></html>`;

const job = await openIsolatedPage({ html, javaScript: true, mounts: [{ prefix: "/fonts/", dir: path.join(ROOT, "fonts") }], extraFiles: files });
await job.page.goto(`${ASSET_ORIGIN}/doc.html`);
await job.page.evaluate(() => document.fonts.ready.then(() => 0));
const pdf = await job.page.pdf({ preferCSSPageSize: true, printBackground: true });
await writeFile(path.join(QA, "contact-sheet.pdf"), pdf);
await job.page.setViewportSize({ width: 1600, height: 1000 });
await job.page.emulateMedia({ media: "screen" });
const sectionsEls = await job.page.locator("section").all();
for (const [i, el] of sectionsEls.entries()) {
  await el.screenshot({ path: path.join(OUT, `${String(i + 1).padStart(2, "0")}.png`) });
}
await job.close();
await closeBrowser();
console.log(`qa/contact-sheet.pdf (${(pdf.length / 1024).toFixed(0)} KB), ${sectionsEls.length} PNGs in qa/contact/`);
