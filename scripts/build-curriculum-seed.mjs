// Builds the seed of public.curriculum_lessons for one Oxford Discover 2nd edition
// level from the school's own copy of that level's Teacher's Guide.
//
//   node scripts/build-curriculum-seed.mjs <teachers-guide.pdf> <level> > supabase/migrations/<ts>_od2e_level<N>_lessons.sql
//
// Needs pdftotext (poppler). Keeps only what a lesson report needs as context:
// the lesson's name and Student Book page, its objective sentence, and the short
// labelled facts the guide lists beside it (words, reading strategy, grammar
// point, listening / speaking / word study / writing focus, Big Question
// learning point). No teaching notes are copied.
import { execFileSync } from "node:child_process";

const [pdf, levelArg] = process.argv.slice(2);
const level = Number(levelArg);
if (!pdf || !Number.isInteger(level)) {
  console.error("usage: build-curriculum-seed.mjs <teachers-guide.pdf> <level>");
  process.exit(1);
}
const text = execFileSync("pdftotext", [pdf, "-"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

const LABELS = [
  "Vocabulary", "Words in context", "Reading strategy", "Big Question learning point", "Materials",
  "School subject", "Text type", "Reading", "Grammar input", "Grammar practice", "Grammar production",
  "Listening strategy", "Speaking", "Word Study", "Writing Study", "Writing task", "Writing", "Project",
];
const labelRe = new RegExp(`\\s(${LABELS.map((l) => l.replace(/ /g, "\\s")).join("|")}):\\s`, "g");
const clean = (s) => s.replace(/[�•●\u0095]/g, " ").replace(/\s+/g, " ").trim();

function fields(block) {
  // block = "Objectives: ... Label: value Label: value ..." up to the first activity heading
  const out = {};
  const parts = (" " + block).split(labelRe);
  out.objectives = clean(parts[0]).replace(/^Objectives:\s*/, "");
  for (let i = 1; i < parts.length; i += 2) out[parts[i].replace(/\s+/g, " ")] = clean(parts[i + 1] ?? "");
  return out;
}

const rows = [];
let bigQuestion = new Map(); // "11-12" -> question
for (const page of text.split("\f")) {
  const flat = clean(page);
  for (const bq of flat.matchAll(/Units (\d+) and (\d+) ((?:How|What|Why|Where|Who|When|Which|Do|Does|Is|Are|Can|Should)\b[^?.]{3,90}\?)/g)) {
    if (!bigQuestion.has(`${bq[1]}-${bq[2]}`)) bigQuestion.set(`${bq[1]}-${bq[2]}`, bq[3].trim());
  }
  const h = flat.match(/(?:^|\s)Units? (\d+)(?: and (\d+))? (Get Ready|Read|Understand|Communicate|Big Question|Wrap Up)\s*page\s*(\d+)/);
  if (!h || !/Objectives:/.test(flat)) continue;
  const start = flat.indexOf("Objectives:");
  // The summary box ends where the activities start: "Materials:" is its last label.
  const mat = flat.indexOf("Materials:", start);
  const end = mat > 0 ? flat.indexOf(" ", flat.indexOf(",", mat) > 0 ? mat + 10 : mat) : start + 700;
  const f = fields(flat.slice(start, mat > 0 ? mat : start + 700));
  const unitFrom = Number(h[1]);
  const unitTo = h[2] ? Number(h[2]) : unitFrom;
  const lesson = h[3];
  // Two-column pages (Big Question) break the objective sentence; use the guide's stated aim.
  if (lesson === "Big Question") f.objectives = "To activate students' existing knowledge of the topic and identify what they would like to learn about the topic.";
  f.objectives = f.objectives.replace(/\s*\d+\s*$/, "").replace(/\s(?:Summary|ANSWERS|COLLABORATIVE LEARNING|CRITICAL THINKING|DIFFERENTIATION).*$/, "");
  if (!/^To /.test(f.objectives)) continue;
  const list = (s) => (s ? s.split(/,\s*/).map((w) => w.trim()).filter(Boolean) : []);
  rows.push({
    unit_from: unitFrom, unit_to: unitTo, lesson, sb_page: Number(h[4]),
    objectives: f.objectives.split(/;\s*/).map((s) => s.replace(/\.$/, "").trim()).filter(Boolean),
    vocabulary: list(f["Vocabulary"]),
    words_in_context: list(f["Words in context"]),
    reading_strategy: f["Reading strategy"] || null,
    grammar: f["Grammar input"] || null,
    focus: Object.fromEntries(
      [["text_type", "Text type"], ["listening", "Listening strategy"], ["speaking", "Speaking"], ["word_study", "Word Study"],
        ["writing_study", "Writing Study"], ["writing_task", "Writing task"], ["writing", "Writing"], ["project", "Project"],
        ["big_question_point", "Big Question learning point"]]
        .filter(([, k]) => f[k]).map(([key, k]) => [key, f[k].slice(0, 240)]),
    ),
  });
}
for (const r of rows) {
  const pairStart = r.unit_from % 2 === 1 ? r.unit_from : r.unit_from - 1;
  r.big_question = bigQuestion.get(`${pairStart}-${pairStart + 1}`) ?? null;
}

const q = (s) => (s === null || s === undefined ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `ARRAY[${a.map(q).join(", ")}]::text[]`;
console.log(`-- Oxford Discover 2nd edition, Level ${level}: one row per lesson in the Teacher's Guide
-- (Get Ready, Read, Understand, Communicate, and the Big Question / Wrap Up pages of each unit pair).
-- Generated by scripts/build-curriculum-seed.mjs from the school's own Teacher's Guide; do not edit by hand.
-- Needs 20261121150000_curriculum_lessons.sql. Safe to run twice (it updates in place).
BEGIN;
INSERT INTO public.curriculum_lessons
  (curriculum, level, unit_from, unit_to, lesson, sb_page, objectives, vocabulary, words_in_context, reading_strategy, grammar, focus, big_question)
VALUES`);
console.log(rows.map((r) => `  ('oxford-discover-2e', ${level}, ${r.unit_from}, ${r.unit_to}, ${q(r.lesson)}, ${r.sb_page}, ${arr(r.objectives)}, ${arr(r.vocabulary)}, ${arr(r.words_in_context)}, ${q(r.reading_strategy)}, ${q(r.grammar)}, ${q(JSON.stringify(r.focus))}::jsonb, ${q(r.big_question)})`).join(",\n"));
console.log(`ON CONFLICT (curriculum, level, unit_from, lesson) DO UPDATE SET
  unit_to = EXCLUDED.unit_to, sb_page = EXCLUDED.sb_page, objectives = EXCLUDED.objectives, vocabulary = EXCLUDED.vocabulary,
  words_in_context = EXCLUDED.words_in_context, reading_strategy = EXCLUDED.reading_strategy, grammar = EXCLUDED.grammar,
  focus = EXCLUDED.focus, big_question = EXCLUDED.big_question;
COMMIT;`);
console.error(`${rows.length} lessons`);
