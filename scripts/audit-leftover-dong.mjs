#!/usr/bin/env node
// Tuition audit, phase 4 (docs/TUITION_AUDIT_ROLLOUT.md): take the 1- and
// 2-dong leftovers off bills that charge nothing (a 100%-discount account).
//
// Every change is a correction through public.record_admin_payment
// (migration 20261117121000): a payments row of minus the leftover, both
// ledger legs, and the bill's recorded_payment by compare-and-set, in one
// transaction, memo "audit: edit leftover". Nothing writes a bill directly.
//
// SAFE BY DEFAULT
//   - Without --write it only reports which bills it would correct. It reads
//     a file and writes nothing.
//   - --write <folder> writes two SQL files there, to paste into the Supabase
//     SQL editor in this order:
//       leftover-dryrun.sql   makes the corrections, shows the bills, ROLLBACK
//       leftover-apply.sql    the same, COMMIT
//   - Each call passes the leftover it saw as p_expected_recorded, so a bill
//     that changed since the file was read is refused (RP412) and the whole
//     paste is rolled back. Each correction's payment id is worked out from
//     the bill's id, so pasting apply twice is refused (RP409), not doubled.
//
// USE
//   1. In the SQL editor run the query `node scripts/audit-leftover-dong.mjs --query`
//      prints, and save the result as JSON (the editor's export).
//   2. node scripts/audit-leftover-dong.mjs --from <that file>
//   3. node scripts/audit-leftover-dong.mjs --from <that file> --admin <your admin user id> --write <folder>
//      The admin id is your auth user id (the corrections are recorded as
//      yours); keep the folder outside the repo, the file names children's ids.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const MEMO = "audit: edit leftover";
export const METHOD = "adjustment"; // not "cash": the ledger leg goes to BANK, as for any non-cash method
export const MAX_DONG = 2;

export const SELECT_SQL = `SELECT i.id AS invoice_id, i.student_id, i.month, i.base_amount, i.discount_amount, i.total_amount,
       i.recorded_payment, i.tuition_frozen, i.status::text AS status
  FROM public.invoices i
 WHERE i.total_amount = 0 AND i.recorded_payment BETWEEN 1 AND ${MAX_DONG}
 ORDER BY i.student_id, i.month;`;

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

// One fixed payment id per bill: the same file always gives the same keys.
export function correctionId(invoiceId) {
  const h = createHash("sha256").update(`audit-leftover:${invoiceId}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-${((parseInt(h[16], 16) & 3) | 8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

// Which bills, and the correction for each. Rows that do not qualify are
// returned as skipped with the reason, never silently dropped.
export function planLeftovers(rows) {
  const take = [];
  const skipped = [];
  for (const r of rows) {
    const rec = Number(r.recorded_payment);
    const total = Number(r.total_amount);
    const why =
      !UUID.test(String(r.invoice_id ?? "")) || !UUID.test(String(r.student_id ?? "")) ? "bad id"
      : !/^\d{4}-(0[1-9]|1[0-2])$/.test(String(r.month ?? "")) ? "bad month"
      : !Number.isInteger(total) || total !== 0 ? "the bill charges something"
      : !Number.isInteger(rec) || rec < 1 || rec > MAX_DONG ? `not a 1-${MAX_DONG} dong leftover`
      : null;
    if (why) { skipped.push({ ...r, why }); continue; }
    take.push({
      invoice_id: r.invoice_id, student_id: r.student_id, month: r.month,
      amount: rec, expected_recorded: rec, payment_id: correctionId(r.invoice_id),
      frozen: r.tuition_frozen === true || r.tuition_frozen === "true",
    });
  }
  return { take, skipped, total: take.reduce((s, x) => s + x.amount, 0) };
}

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

export function buildSql(plan, { admin, commit }) {
  if (!UUID.test(String(admin ?? ""))) throw new Error("--admin must be your admin user id (a uuid)");
  const lines = [
    `-- Tuition audit phase 4: ${plan.take.length} leftover correction(s), ${plan.total} dong in all.`,
    `-- ${commit ? "APPLY: commits." : "DRY RUN: makes the corrections, shows the bills, then rolls everything back."}`,
    `-- Generated by scripts/audit-leftover-dong.mjs. Each call refuses if the bill changed since it was read.`,
    "BEGIN;",
    `SELECT set_config('request.jwt.claims', ${lit(JSON.stringify({ sub: admin, role: "authenticated" }))}, true);`,
    "SET LOCAL ROLE authenticated;",
  ];
  for (const x of plan.take) {
    lines.push(
      `SELECT public.record_admin_payment(${lit(x.payment_id)}::uuid, ${lit(x.student_id)}::uuid, ${lit(x.month)}, 'correction', ${x.amount}, ${lit(METHOD)}, now(), ${lit(MEMO)}, ${x.expected_recorded});`,
    );
  }
  const ids = plan.take.map((x) => `${lit(x.invoice_id)}::uuid`).join(", ") || "NULL::uuid";
  lines.push(
    `SELECT i.student_id, i.month, i.total_amount, i.recorded_payment, i.status::text AS status FROM public.invoices i WHERE i.id IN (${ids}) ORDER BY i.student_id, i.month;`,
    commit ? "COMMIT;" : "ROLLBACK;",
    "",
  );
  return lines.join("\n");
}

function main(argv) {
  const arg = (name) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined; };
  if (argv.includes("--query")) { console.log(SELECT_SQL); return 0; }
  const from = arg("--from");
  if (!from) {
    console.error("usage: --query | --from <rows.json> [--admin <uuid> --write <folder>]");
    return 2;
  }
  const raw = JSON.parse(readFileSync(from, "utf8"));
  const rows = Array.isArray(raw) ? raw : raw.rows ?? raw.result ?? [];
  const plan = planLeftovers(rows);
  for (const x of plan.take) {
    console.log(`  correct ${x.month} bill ${x.invoice_id} of ${x.student_id}: -${x.amount} dong${x.frozen ? " (bill is frozen; its charge is not touched)" : ""}`);
  }
  for (const s of plan.skipped) console.log(`  skip ${s.month ?? "?"} bill ${s.invoice_id ?? "?"}: ${s.why}`);
  console.log(`${plan.take.length} correction(s), ${plan.total} dong; ${plan.skipped.length} skipped.`);
  const out = arg("--write");
  if (!out) { console.log("Dry run: nothing written. Add --admin <uuid> --write <folder> for the SQL files."); return 0; }
  const admin = arg("--admin");
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "leftover-dryrun.sql"), buildSql(plan, { admin, commit: false }));
  writeFileSync(join(out, "leftover-apply.sql"), buildSql(plan, { admin, commit: true }));
  console.log(`Wrote ${join(out, "leftover-dryrun.sql")} and leftover-apply.sql. Paste the dry run first.`);
  return 0;
}

if (process.argv[1] && resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1])) {
  process.exit(main(process.argv.slice(2)));
}
