  "Listen and do not stop the talk. Note two or three mistakes you hear (no names): the usual ones are 'They was', 'I were', 'Yes, it were', 'Was the students happy?' and a missing be ('The ice hard'). Between rounds 1 and 2 stop for one minute: write the mistakes on the board and let the class fix them; students then say it again with the fixed form. For grammar, prompt the student to fix it: start the phrase and pause ('The cups w...?'), point to the was / were frame, or repeat the error with a rising voice ('They WAS?'). For a sound, say it right and let the student echo it. Say was, were and the -n't of wasn't and weren't clearly yourself.";

