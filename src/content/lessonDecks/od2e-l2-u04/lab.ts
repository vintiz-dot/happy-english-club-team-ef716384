const fixCause =
  "Listen and do not stop the talk. Note two or three mistakes you hear (no names): the usual ones are a missing -s ('the ice melt'), 'When it is hot, the ice' with no effect, a missing 'so', and 'because' with no reason after it. Between rounds 1 and 2 stop for one minute: write the mistakes on the board and let the class fix them; students then say it again with the fixed form. For grammar, prompt the student to fix it instead of saying it for them: start the phrase and pause ('When it is hot, the ice mel...?'), point to the frame, or tap your wrist for the missing -s. For a sound, say it right and let the student echo it. Say every final -s yourself, clearly.";

