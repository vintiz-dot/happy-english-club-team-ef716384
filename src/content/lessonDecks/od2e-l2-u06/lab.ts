  "During a round, listen and do not stop the talk. Note two or three mistakes you hear (no names). Between round 1 and round 2, write them on the board and let the class fix them in one minute: students who then say it again use the fixed form. For grammar, prompt the student to fix it: point to the frame, start the phrase and pause ('Did you ...?'), hold up a finger for the missing -ed, or repeat the error with a rising voice ('Did you played?'). Do not say the right form for them. For a sound, just say it right and let them echo it. Say every final -ed and -s clearly yourself: Vietnamese speakers often leave off the -ed of 'visited' and 'traveled', so exaggerate it a little ('visit-ed', 'travel-d').";

